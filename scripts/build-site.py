#!/usr/bin/env python3
"""Build the landing page's language versions from site/index.html.

site/index.html is the one file you edit. Every visible string in it already
has a Chinese and an English version (<span class="zh"> / <span class="en">);
CSS shows one of them by <html lang>. This script

  * rewrites the SEO block in site/index.html's <head> (between the
    seo:begin / seo:end markers) for the Chinese page at /,
  * writes site/en/index.html, the same page with lang="en" and an English
    SEO block, served at /en/,
  * writes site/sitemap.xml listing both, with hreflang alternates.

Run it after editing site/index.html:

    scripts/build-site.py           # write the files
    scripts/build-site.py --check   # CI: fail if they are out of date
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "site"
SITE = "https://agentdeck.cassianflorin.com"
REPO = "https://github.com/CassianFlorin/AgentDeck"

LANGS = {
    "zh": {
        "html_lang": "zh-Hans",
        "path": "/",
        "og_locale": "zh_CN",
        "title": "AgentDeck — 一个窗口，看住所有编程 Agent | macOS",
        "desc": "AgentDeck 是一个原生 macOS 应用，用来并排运行多个 AI 编程 Agent（Claude Code、Codex、Gemini 等），"
                "本地和 SSH 服务器上的都行，一条侧边栏告诉你哪个 Agent 在等你。基于 Ghostty，免费开源。",
        "og_title": "AgentDeck：一个窗口，看住所有编程 Agent",
        "og_image": "/og.png",
        "og_image_alt": "AgentDeck：侧边栏里并排的多个编程 Agent，各自显示运行中、等你等状态",
        "lang_link": "/en/",
    },
    "en": {
        "html_lang": "en",
        "path": "/en/",
        "og_locale": "en_US",
        "title": "AgentDeck — One window for every coding agent on macOS",
        "desc": "AgentDeck is a native macOS app for running multiple AI coding agents (Claude Code, Codex, Gemini and more) "
                "side by side, locally or over SSH, with one sidebar that shows which agent needs you. Built on Ghostty. Free and open source.",
        "og_title": "AgentDeck: one window for every coding agent",
        "og_image": "/og-en.png",
        "og_image_alt": "AgentDeck: several coding agents side by side in a sidebar, each showing whether it is working or waiting",
        "lang_link": "/",
    },
}

BEGIN, END = "<!-- seo:begin (generated by scripts/build-site.py) -->", "<!-- seo:end -->"


def esc(s):
    return s.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")


def faq(src, key):
    """The FAQ section's questions and answers, as plain text in one language."""
    pair = re.compile(r'<span class="zh">(.*?)</span><span class="en">(.*?)</span>', re.S)
    out = []
    for q, a in re.findall(r'<div class="faq-item">\s*<h3>(.*?)</h3>\s*<p>(.*?)</p>', src, re.S):
        pick = lambda html: pair.search(html).group(1 if key == "zh" else 2)
        text = lambda html: re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", html)).strip()
        out.append({"@type": "Question", "name": text(pick(q)),
                    "acceptedAnswer": {"@type": "Answer", "text": text(pick(a))}})
    return out


def ld_script(data):
    return ('<script type="application/ld+json">\n  '
            + json.dumps(data, ensure_ascii=False, indent=2).replace("\n", "\n  ")
            + "\n  </script>")


def seo_block(key, src):
    c = LANGS[key]
    other = "en" if key == "zh" else "zh"
    ld = {
        "@context": "https://schema.org",
        "@type": "SoftwareApplication",
        "name": "AgentDeck",
        "url": SITE + c["path"],
        "description": c["desc"],
        "inLanguage": c["html_lang"],
        "applicationCategory": "DeveloperApplication",
        "operatingSystem": "macOS 14 or later",
        "softwareRequirements": "Apple silicon",
        "downloadUrl": REPO + "/releases/latest",
        "installUrl": REPO + "/releases/latest",
        "screenshot": SITE + c["og_image"],
        "image": SITE + "/icon.png",
        "license": "https://opensource.org/licenses/MIT",
        "isAccessibleForFree": True,
        "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
        "author": {"@type": "Person", "name": "CassianFlorin", "url": "https://github.com/CassianFlorin"},
        "sameAs": [REPO],
    }
    # A visitor who picked the other language with the toggle goes straight
    # there. Crawlers have no stored choice, so they always get this page.
    redirect = (
        "(function () {\n"
        '      document.documentElement.classList.add("js");\n'
        "      var pick = null;\n"
        '      try { pick = localStorage.getItem("agentdeck-lang"); } catch (e) {}\n'
        f'      if (pick === "{other}") location.replace("{LANGS[other]["path"]}" + location.hash);\n'
        "    })();"
    )
    lines = [
        BEGIN,
        f"<title>{c['title']}</title>",
        f'<meta name="description" content="{esc(c["desc"])}">',
        f'<link rel="canonical" href="{SITE}{c["path"]}">',
        f'<link rel="alternate" hreflang="zh-Hans" href="{SITE}/">',
        f'<link rel="alternate" hreflang="en" href="{SITE}/en/">',
        f'<link rel="alternate" hreflang="x-default" href="{SITE}/en/">',
        '<link rel="icon" href="/favicon.png" type="image/png">',
        '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="AgentDeck">',
        f'<meta property="og:title" content="{esc(c["og_title"])}">',
        f'<meta property="og:description" content="{esc(c["desc"])}">',
        f'<meta property="og:url" content="{SITE}{c["path"]}">',
        f'<meta property="og:locale" content="{c["og_locale"]}">',
        f'<meta property="og:locale:alternate" content="{LANGS[other]["og_locale"]}">',
        f'<meta property="og:image" content="{SITE}{c["og_image"]}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{esc(c["og_image_alt"])}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{esc(c["og_title"])}">',
        f'<meta name="twitter:description" content="{esc(c["desc"])}">',
        f'<meta name="twitter:image" content="{SITE}{c["og_image"]}">',
        f"<script>\n    {redirect}\n  </script>",
        ld_script(ld),
        *([ld_script({"@context": "https://schema.org", "@type": "FAQPage", "inLanguage": c["html_lang"],
                      "mainEntity": qa})] if (qa := faq(src, key)) else []),
        END,
    ]
    return "\n  ".join(lines)


def page(src, key):
    c = LANGS[key]
    out, n = re.subn(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: seo_block(key, src), src, flags=re.S)
    assert n == 1, "SEO markers not found in site/index.html"
    out, n = re.subn(r'<html lang="[^"]*">', f'<html lang="{c["html_lang"]}">', out, count=1)
    assert n == 1, "<html lang> not found"
    out, n = re.subn(r'(<a [^>]*id="lang"[^>]*href=")[^"]*(")', lambda m: m.group(1) + c["lang_link"] + m.group(2), out)
    assert n == 1, "language toggle link not found"
    return out


def sitemap():
    urls = []
    for key in ("zh", "en"):
        alts = "".join(
            f'\n    <xhtml:link rel="alternate" hreflang="{LANGS[k]["html_lang"]}" href="{SITE}{LANGS[k]["path"]}"/>'
            for k in ("zh", "en")
        )
        urls.append(f"  <url>\n    <loc>{SITE}{LANGS[key]['path']}</loc>{alts}\n  </url>")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + "\n".join(urls)
        + "\n</urlset>\n"
    )


def main():
    check = "--check" in sys.argv[1:]
    src = (ROOT / "index.html").read_text(encoding="utf-8")
    outputs = {
        ROOT / "index.html": page(src, "zh"),
        ROOT / "en" / "index.html": page(src, "en"),
        ROOT / "sitemap.xml": sitemap(),
    }
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(ROOT.parent))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if check and stale:
        print("Out of date, run scripts/build-site.py: " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    print("up to date" if not stale else "wrote " + ", ".join(map(str, stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
